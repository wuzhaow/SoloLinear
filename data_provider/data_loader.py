class Dataset_Battery(Dataset):
    def __init__(self, args, root_path, flag='train', size=None,
                 features='S', data_path='ETTh1.csv',
                 target='OT', scale=True, timeenc=0, freq='h', seasonal_patterns=None):
        # size [seq_len, label_len, pred_len]
        self.args = args
        # info
        if size == None:
            self.seq_len = 24 * 4 * 4
            self.label_len = 24 * 4
            self.pred_len = 24 * 4
        else:
            self.seq_len = size[0]
            self.label_len = size[1]
            self.pred_len = size[2]
        # init
        assert flag in ['train', 'test', 'val']
        type_map = {'train': 0, 'val': 1, 'test': 2}
        self.set_type = type_map[flag]
        self.features = features
        self.target = target
        self.scale = scale
        self.freq = freq
        self.root_path = root_path
        self.data_path = data_path
        self.__read_data__()



    def __read_data__(self):
        self.scaler = StandardScaler()
        df_raw = pd.read_csv(os.path.join(self.root_path, self.data_path))

        # 1. 预处理数据
        cols = list(df_raw.columns)
        cols.remove(self.target)
        df_raw = df_raw[cols + [self.target]]

        # 保存原始数据供后续使用
        self.df_raw = df_raw

        # 2. 识别不同电池的边界
        battery_boundaries = [0]  # 第一个电池的起始位置
        ot_values = df_raw[self.target].values

        for i in range(1, len(ot_values)):
            prev_ot = ot_values[i - 1]
            curr_ot = ot_values[i]

            # 如果OT值增加，说明是新电池的开始
            if curr_ot > prev_ot:
                battery_boundaries.append(i)

        battery_boundaries.append(len(df_raw))  # 最后一个电池的结束位置

        # 保存电池边界供后续使用
        self.battery_boundaries = battery_boundaries

        # 3. 将不同电池的数据分别放在不同的列表中
        battery_segments = []
        for i in range(len(battery_boundaries) - 1):
            start_idx = battery_boundaries[i]
            end_idx = battery_boundaries[i + 1]
            segment = df_raw.iloc[start_idx:end_idx].copy()
            battery_segments.append(segment)

        # 保存电池段供后续使用
        self.battery_segments = battery_segments

        # 4. 处理特征选择
        if self.features == 'M' or self.features == 'MS' or self.features == "N":
            cols_data = df_raw.columns[:]
        elif self.features == 'S':
            cols_data = [self.target]

        self.cols_data = cols_data

        # 5. 为每个电池创建单独的StandardScaler
        self.scalers = []
        if self.scale:
            for i, segment in enumerate(battery_segments):
                segment_len = len(segment)
                train_end = int(segment_len * 0.6)

                # 为每个电池创建一个专用的scaler
                scaler = StandardScaler()

                # 使用该电池的训练部分进行拟合
                if train_end > 0:
                    scaler.fit(segment[cols_data].iloc[:train_end].values)
                else:
                    # 如果电池数据太少，使用全部数据拟合
                    print(f"警告：电池 {i} 的训练数据不足，使用全部数据拟合scaler")
                    scaler.fit(segment[cols_data].values)

                self.scalers.append(scaler)

            # 保留一个全局scaler用于inverse_transform
            self.scaler = StandardScaler()
            # 使用所有电池的训练部分进行拟合（仅用于可能的全局逆变换）
            all_train_data = []
            for segment in battery_segments:
                segment_len = len(segment)
                train_end = int(segment_len * 0.6)
                if train_end > 0:
                    all_train_data.append(segment[cols_data].iloc[:train_end])

            if all_train_data:
                self.scaler.fit(pd.concat(all_train_data).values)
            else:
                print("警告：找不到训练数据，使用全部数据拟合全局scaler")
                self.scaler.fit(df_raw[cols_data].values)

        # 6. 为每个电池段创建滑动窗口
        all_x_windows = []
        all_y_windows = []

        # 记录每个窗口来自哪个电池段
        self.window_to_battery_map = []
        self.window_start_indices = []

        for battery_idx, segment in enumerate(battery_segments):
            if len(segment) < self.seq_len + self.pred_len:
                print(f"跳过太短的电池段 {battery_idx} (长度: {len(segment)})")
                continue

            # 按比例划分此电池的数据
            segment_len = len(segment)
            train_end = int(segment_len * 0.6)
            val_end = int(segment_len * 0.8)

            # 确定当前使用哪部分数据（训练/验证/测试）
            if self.set_type == 0:  # 训练集
                if train_end <= self.seq_len + self.pred_len:
                    print(f"跳过训练集太短的电池段 {battery_idx} (有效长度: {train_end})")
                    continue
                use_start, use_end = 0, train_end
            elif self.set_type == 1:  # 验证集
                if val_end - train_end <= self.seq_len + self.pred_len:
                    print(f"跳过验证集太短的电池段 {battery_idx} (有效长度: {val_end - train_end})")
                    continue
                use_start, use_end = train_end, val_end
            else:  # 测试集
                if segment_len - val_end <= self.seq_len + self.pred_len:
                    print(f"跳过测试集太短的电池段 {battery_idx} (有效长度: {segment_len - val_end})")
                    continue
                use_start, use_end = val_end, segment_len

            # 获取需要的列
            segment_data = segment[cols_data].values

            # 设置标记，表示我们已经获取了原始数据的数值
            self.segments_normalized = False

            # 使用该电池专属的scaler进行标准化
            if self.scale:
                # 使用对应电池的scaler进行标准化
                segment_data = self.scalers[battery_idx].transform(segment_data)

            # 为这个电池段创建滑动窗口
            max_window_start = use_end - self.seq_len - self.pred_len + 1
            for i in range(use_start, max_window_start):
                x_start = i
                x_end = x_start + self.seq_len
                y_start = x_end - self.label_len
                y_end = y_start + self.label_len + self.pred_len

                if y_end <= use_end:  # 确保窗口不会超出当前段的边界
                    x_window = segment_data[x_start:x_end]
                    y_window = segment_data[y_start:y_end]
                    all_x_windows.append(x_window)
                    all_y_windows.append(y_window)

                    # 记录窗口来源
                    self.window_to_battery_map.append(battery_idx)
                    self.window_start_indices.append(x_start)

        # 7. 将所有窗口转换为numpy数组
        if len(all_x_windows) == 0:
            raise ValueError(
                f"No valid windows found for {self.set_type} set. Try reducing window sizes or adjusting split ratios.")

        self.all_x_windows = np.array(all_x_windows)
        self.all_y_windows = np.array(all_y_windows)

        # 保存当前集合的有效电池段
        self._get_valid_segments()

        # 8. 保存归一化的数据到CSV (只在训练集初始化时保存)
        if self.set_type == 0:  # 只在训练集时保存归一化数据
            self.save_normalized_data_to_csv()

    def save_normalized_data_to_csv(self, output_path=None):
        """
        将归一化后的数据保存到CSV文件中

        Args:
            output_path: 输出CSV文件的路径。如果为None，则使用原始数据路径并添加'_normalized'后缀

        Returns:
            保存的CSV文件路径
        """
        import os

        if output_path is None:
            # 从原始数据路径创建输出路径
            filename = os.path.basename(self.data_path)
            name, ext = os.path.splitext(filename)
            output_path = os.path.join(self.root_path, f"{name}_normalized{ext}")

        # 创建一个空的DataFrame用于存储所有归一化的数据
        import pandas as pd
        normalized_data_frames = []

        # 对每个电池段进行处理
        for battery_idx, segment in enumerate(self.battery_segments):
            if battery_idx not in range(len(self.scalers)):
                print(f"跳过电池段 {battery_idx}：没有对应的scaler")
                continue

            # 获取原始数据
            segment_data = segment[self.cols_data].values

            # 使用对应电池的scaler进行标准化
            if self.scale:
                normalized_segment_data = self.scalers[battery_idx].transform(segment_data)
            else:
                normalized_segment_data = segment_data

            # 创建DataFrame
            normalized_df = pd.DataFrame(
                normalized_segment_data,
                columns=self.cols_data
            )

            # 添加电池ID列
            normalized_df['battery_id'] = battery_idx

            # 添加原始索引
            normalized_df['original_index'] = segment.index

            # 如果有其他需要保留的列（如时间戳），可以在此添加
            for col in segment.columns:
                if col not in self.cols_data:
                    normalized_df[col] = segment[col].values

            # 将此电池段添加到结果中
            normalized_data_frames.append(normalized_df)

        # 合并所有电池段的数据
        if normalized_data_frames:
            all_normalized_data = pd.concat(normalized_data_frames, axis=0)

            # 保存到CSV
            all_normalized_data.to_csv(output_path, index=False)
            print(f"归一化数据已保存至: {output_path}")
            return output_path
        else:
            print("没有找到可用的电池段数据")
            return None

    def _get_valid_segments(self):
        """获取当前集合（训练/验证/测试）中有效的电池段"""
        valid_segments = []
        valid_segment_indices = []

        for battery_idx, segment in enumerate(self.battery_segments):
            segment_len = len(segment)
            train_end = int(segment_len * 0.6)
            val_end = int(segment_len * 0.8)

            if self.set_type == 0:  # 训练集
                if train_end > self.seq_len + self.pred_len:
                    valid_segments.append(segment.iloc[:train_end])
                    valid_segment_indices.append(battery_idx)
            elif self.set_type == 1:  # 验证集
                if val_end - train_end > self.seq_len + self.pred_len:
                    valid_segments.append(segment.iloc[train_end:val_end])
                    valid_segment_indices.append(battery_idx)
            else:  # 测试集
                if segment_len - val_end > self.seq_len + self.pred_len:
                    valid_segments.append(segment.iloc[val_end:])
                    valid_segment_indices.append(battery_idx)

        self.valid_segments = valid_segments
        self.valid_segment_indices = valid_segment_indices

    def __getitem__(self, index):
        # 直接从预先计算好的窗口中获取数据
        seq_x = self.all_x_windows[index]
        seq_y = self.all_y_windows[index]

        return seq_x, seq_y, seq_x, seq_y, seq_y

    def __len__(self):
        return len(self.all_x_windows)

    def inverse_transform(self, data, battery_idx=None):
        """
        将标准化的数据转换回原始尺度

        Args:
            data: 需要逆变换的数据
            battery_idx: 电池索引，如果提供，则使用该电池的scaler；否则使用全局scaler

        Returns:
            逆变换后的数据
        """
        if battery_idx is not None and self.scale and 0 <= battery_idx < len(self.scalers):
            # 使用指定电池的scaler进行逆变换
            return self.scalers[battery_idx].inverse_transform(data)
        else:
            # 使用全局scaler进行逆变换（可能不如使用特定电池的scaler准确）
            return self.scaler.inverse_transform(data)




